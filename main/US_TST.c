/*  This code generates two waveforms from the ESP32-S3:
 *   1) BURST -- a series of pulse_count pulses at ~1.8 MHz, optionally followed
 *      by a hold at hold_level
 *   2) GATE -- an enabling signal, an envelope around the burst: held at its
 *      active level for the pulses and the hold, idle otherwise. In the usual
 *      wiring it gates a line driver into a high-impedance state so the crystal
 *      can ring freely; see the header for the other wiring.
 *
 *  Which logic level is "active" is a per-signal choice made by the preset
 *  (burst_active_level / gate_active_level), so neither signal is tied to a rail:
 *  the pulses can drive high out of a low-resting line or low out of a
 *  high-resting one, and the gate independently either way. set_burst_active() /
 *  set_gate_active() resolve those flags into the level pairs that the symbol
 *  tables and the channel configs are then built from.
 *
 *  The numbers come from the active burst_config_t -- see the cfg_* presets and
 *  ACTIVE_CONFIG immediately below.
 *
 *  The two waveforms must be aligned in time precisely. An earlier version drove
 *  the gate from a general purpose timer; that could not hold the required
 *  synchronization against the pulses. Both signals are now generated by two
 *  channels of the RMT peripheral, tied together by the RMT TX *sync manager*.
 *
 *  The sync manager is the hardware feature that makes this exact: once channels
 *  are added to it, a channel's tx_start is held until every channel in the group
 *  has been started, so both channels leave the peripheral on the same clock edge
 *  regardless of the latency between the two rmt_transmit() calls. Requirements:
 *    - TX channels only, all in the same RMT group
 *    - identical clock source and resolution_hz
 *    - all channels rmt_enable()d *before* rmt_new_sync_manager() is called
 *    - rmt_sync_reset() before every new synchronized round, otherwise the second
 *      and later bursts drift apart.
 */

static const char *TAG = "rmt_burst test";

